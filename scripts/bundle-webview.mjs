/**
 * Bundle the webview script and stylesheet into a generated TypeScript module.
 *
 * The panel used to read its compiled dependencies off disk on every resolve.
 * Bundling here removes those reads entirely, and a name the script imports
 * that does not exist fails this build rather than silently disabling a slider.
 *
 * Identifiers are deliberately left alone while whitespace and syntax are
 * squeezed: the rendered html is what the panel tests read, and a mangled
 * `hexToHsl` would make those assertions meaningless.
 */

import { build } from "esbuild";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const entry = join(root, "src", "webview", "panel.ts");
const stylesheet = join(root, "src", "webview", "panel.css");
const target = join(root, "src", "generated", "webviewAssets.ts");

const bundled = await build({
  entryPoints: [entry],
  bundle: true,
  format: "iife",
  target: "es2020",
  minifyWhitespace: true,
  minifySyntax: true,
  minifyIdentifiers: false,
  write: false,
});

const script = bundled.outputFiles[0].text;
const css = await readFile(stylesheet, "utf8");

await mkdir(dirname(target), { recursive: true });
await writeFile(
  target,
  "// Generated by scripts/bundle-webview.mjs — do not edit.\n" +
    `export const panelScript = ${JSON.stringify(script)};\n` +
    `export const panelCss = ${JSON.stringify(css)};\n`,
  "utf8"
);
